//! MCP (Model Context Protocol) server exposing text-editor tools
//! scoped to a single workspace directory.
//! All paths, relative or absolute, are resolved against the workspace root
//! and rejected if they would escape it.
mod create;
mod insert;
mod just_run;
mod recipe_run;
mod str_replace;
mod tree;
mod view;
mod workspace_path;

pub(crate) use just_run::RecipeName as JustRecipeName;
pub(crate) use recipe_run::discover as discover_recipes;
pub use workspace_path::IgnorePattern;

use recipe::RecipeFile;

use anyhow::Result;
use rmcp::handler::server::router::tool::ToolRouter;
use rmcp::handler::server::tool::ToolCallContext;
use rmcp::model::{
    CallToolRequestParams, CallToolResponse, ErrorData as McpError, Implementation,
    ListToolsResult, PaginatedRequestParams, ServerCapabilities, ServerInfo,
};
use rmcp::service::RequestContext;
use rmcp::{RoleServer, ServerHandler};

use std::borrow::Cow;
use std::collections::BTreeMap;
use std::path::PathBuf;

/// MCP server exposing a text-editor tool, sandboxed to one workspace root.
#[derive(Clone)]
pub struct McpService {
    workspace_root: PathBuf,
    /// Glob patterns treated as nonexistent by every tool, e.g. ".git",
    /// "target", or "*.log" — not just hidden from `tree`, but unreadable,
    /// unwritable, and invisible everywhere a path is resolved. See
    /// [`IgnorePattern`] for the matching rules.
    ///
    /// When [`protect_justfiles`](Self::protect_justfiles) is set, this
    /// also includes [`IgnorePattern::justfile_patterns`]; when
    /// [`recipe_toml_protected_path`](Self::recipe_toml_protected_path)
    /// is `Some`, it also includes an
    /// [`IgnorePattern::exact_path`] for that one path — both added here
    /// in [`McpService::new`], not via `--ignore`, so protection stays
    /// tied to whether each tool is actually offered rather than to
    /// ordinary, user-editable ignore configuration. The two are
    /// independent: either, neither, or both can be active.
    ignore: Vec<IgnorePattern>,
    /// Whether `justfile`/`*.just` are write-refused (`into_write_buffer`)
    /// in addition to being folded into `ignore` above. `true` unless
    /// `just_run` has no recipes to run — see `--enable-just-run` and
    /// ADR 0003: the protection exists only to stop an agent from editing
    /// a recipe it could then run, so it has no purpose once running one
    /// is impossible.
    protect_justfiles: bool,
    /// Recipes discovered once at construction time from `justfile`, with
    /// doc comment and parameter help. Empty map if the workspace has no
    /// `justfile`, or `--enable-just-run` wasn't passed.
    just_recipes: BTreeMap<JustRecipeName, just_run::RecipeInfo>,
    /// The workspace-relative path of the file passed via
    /// `--recipes-file`, write-refused (`into_write_buffer`) and folded
    /// into `ignore` above, if and only if that file actually lies
    /// inside the workspace. `None` covers both "no `--recipes-file`
    /// passed" and "passed, but the file is outside the workspace" — the
    /// latter needs no protection since every tool here already can't
    /// reach outside the workspace root regardless. See ADR 0004's
    /// "More Information" amendment.
    recipe_toml_protected_path: Option<PathBuf>,
    /// Recipes read once at construction time from the path passed via
    /// `--recipes-file`. Empty if that flag wasn't passed or the file
    /// doesn't exist — see ADR 0004.
    recipes: RecipeFile,
    tool_router: ToolRouter<Self>,
}

impl ServerHandler for McpService {
    fn get_info(&self) -> ServerInfo {
        ServerInfo::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new(
                "kid-text-editor",
                env!("CARGO_PKG_VERSION"),
            ))
            .with_instructions(
                "File editor scoped to a single workspace. \
                All paths (relative or absolute) are resolved \
                against the workspace root.",
            )
    }

    /// Not generated by `#[tool_handler]` here, because `just_run`'s and
    /// `recipe_run`'s descriptions are otherwise fixed at compile time —
    /// each can say "runs a recipe" but not *which* recipes this
    /// workspace actually defines, since that's only known once
    /// `just_recipes`/`recipes` are discovered at startup (see ADR 0003,
    /// "a boundary the agent can't see isn't fully useful"). This appends
    /// each tool's list to its already-built description on the way out;
    /// it does not change which recipes are callable — both handlers
    /// still check every call against their own recipe map independently.
    async fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListToolsResult, McpError> {
        let mut tools = self.tool_router.list_all();
        if let Some(just_run) = tools.iter_mut().find(|tool| tool.name == "just_run") {
            let base = just_run.description.as_deref().unwrap_or_default();
            let recipes = self
                .just_recipes
                .iter()
                .map(|(name, info)| {
                    let params = info
                        .arg_names()
                        .map(|arg| arg.as_str())
                        .collect::<Vec<_>>()
                        .join(" ");
                    let mut line = match params.as_str() {
                        "" => name.to_string(),
                        params => format!("{name} {params}"),
                    };
                    if info.has_desc() {
                        line.push_str(&format!(": {}", info.desc()));
                    }
                    if info.has_args() {
                        let help = info
                            .args()
                            .map(|(arg, help)| match help.as_str() {
                                "" => arg.to_string(),
                                help => format!("{arg} — {help}"),
                            })
                            .collect::<Vec<_>>()
                            .join("; ");
                        line.push_str(&format!(" (args: {help})"));
                    }
                    format!("- {line}")
                })
                .collect::<Vec<_>>()
                .join("\n");
            just_run.description =
                Some(Cow::Owned(format!("{base} Available recipes:\n{recipes}")));
        }
        // One tool per `--recipes-file` recipe (see ADR 0005), not
        // routed through `tool_router` — appended here instead of
        // enriching a single description, unlike `just_run` above.
        tools.extend(recipe_run::tools(&self.recipes));
        Ok(ListToolsResult::with_all_items(tools))
    }

    async fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<CallToolResponse, McpError> {
        if request.name == "just_run" && !self.protect_justfiles {
            return Err(McpError::invalid_params(
                "just_run is disabled. If it previously appeared in your tool list, that list is now stale.",
                None,
            ));
        }
        if let Some(result) = recipe_run::call(
            &self.recipes,
            &request.name,
            request.arguments.as_ref(),
            &self.workspace_root,
        ) {
            return result.map(Into::into);
        }
        self.tool_router
            .call(ToolCallContext::new(self, request, context))
            .await
    }
}

impl McpService {
    /// `just_recipes` and `recipes` are each read once by the caller (see
    /// `McpServer::serve`), not per session. Pass empty collections to
    /// leave the corresponding tool disabled — the defaults, absent
    /// `--enable-just-run` and `--recipes-file` respectively. The two
    /// sources are independent: either, neither, or both may be
    /// non-empty. `recipe_toml_protected_path` must already be
    /// confirmed to lie inside `workspace_root` (relative to it) — see
    /// `McpServer::serve`, which does that check before calling this.
    pub fn new(
        workspace_root: PathBuf,
        mut ignore: Vec<IgnorePattern>,
        just_recipes: BTreeMap<JustRecipeName, just_run::RecipeInfo>,
        recipes: RecipeFile,
        recipe_toml_protected_path: Option<PathBuf>,
    ) -> Self {
        let mut tool_router = Self::create_tool_router()
            + Self::insert_tool_router()
            + Self::str_replace_tool_router()
            + Self::tree_tool_router()
            + Self::view_tool_router();

        let protect_justfiles = !just_recipes.is_empty();
        if protect_justfiles {
            tool_router += Self::just_run_tool_router();
            ignore.extend(IgnorePattern::justfile_patterns());
        }

        if let Some(protected) = &recipe_toml_protected_path {
            ignore.push(IgnorePattern::exact_path(protected.clone()));
        }

        Self {
            workspace_root,
            ignore,
            protect_justfiles,
            just_recipes,
            recipe_toml_protected_path,
            recipes,
            tool_router,
        }
    }
}
